/**
 * Compiles network scripts on the vendored Rhino (interpreted mode — ART cannot load
 * generated bytecode — ES6 level, as the original interceptor ran). Pure JVM: every
 * script behaviour is tested without a device (constitution IV).
 */
object ScriptEngine {

    private const val NAME = "network-script.js"
    private val HANDLERS = mapOf(
        ScriptHandler.REQUEST to "onRequest",
        ScriptHandler.RESPONSE to "onResponse",
        ScriptHandler.WS_SEND to "onWsSend",
        ScriptHandler.WS_RECEIVE to "onWsReceive",
    )

    fun compile(source: String, log: ScriptLogSink): CompiledScript {
        val cx = enter()
        try {
            val scope = cx.initStandardObjects()
            val globals = ScriptGlobals(log)
            globals.install(scope)
            val script = try {
                cx.compileString(source, NAME, 1, null)
            } catch (e: EvaluatorException) {
                throw ScriptCompileException("${e.details()} at line ${e.lineNumber()}, column ${e.columnNumber()}", e.lineNumber(), e.columnNumber())
            }
            try {
                script.exec(cx, scope)
            } catch (e: RhinoException) {
                throw ScriptCompileException("script failed while loading: ${e.details()} at line ${e.lineNumber()}", e.lineNumber(), e.columnNumber())
            }
            val handlers = HANDLERS.filter { (_, name) -> ScriptableObject.getProperty(scope, name) is Function }.keys
            if (handlers.isEmpty()) {
                throw ScriptCompileException("script defines none of ${HANDLERS.values.joinToString(", ")}", 0, 0)
            }
            return CompiledScript(scope, globals, handlers, HANDLERS)
        } finally {
            Context.exit()
        }
    }

    internal fun enter(): Context = Context.enter().apply {
        optimizationLevel = -1
        languageVersion = Context.VERSION_ES6
    }
}

/** Per-call bookkeeping read by the global functions (sleep, throttle, log). */
internal class CallState(val handler: ScriptHandler) {
    var delayNanos = 0L
    var throttle: Long? = null
}

/** `sleep`, `throttle`, `log`, `state`, `respond`, `drop`. */
internal class ScriptGlobals(private val log: ScriptLogSink) {
    val current = ThreadLocal<CallState?>()
    private val state = HashMap<String, Any?>()

    fun install(scope: ScriptableObject) {
        fn(scope, "sleep") { args ->
            val ms = Context.toNumber(args.getOrNull(0)).toLong()
            if (ms > 0) {
                val start = System.nanoTime()
                try {
                    Thread.sleep(ms)
                } catch (_: InterruptedException) {
                    Thread.currentThread().interrupt()
                }
                current.get()?.let { it.delayNanos += System.nanoTime() - start }
            }
            Undefined.instance
        }
        fn(scope, "throttle") { args ->
            val call = current.get()
            if (call?.handler != ScriptHandler.RESPONSE) throw IllegalStateException("throttle() is only available in onResponse")
            call.throttle = Context.toNumber(args.getOrNull(0)).toLong().takeIf { it > 0 }
            Undefined.instance
        }
        fn(scope, "log") { args ->
            log(ScriptLogLevel.LOG, current.get()?.handler, args.joinToString(" ") { Context.toString(it) })
            Undefined.instance
        }
        fn(scope, "drop") { marker("drop") }
        fn(scope, "respond") { args ->
            marker("respond").also { m ->
                val spec = args.getOrNull(0) as? Scriptable
                if (spec != null) for (key in spec.ids) ScriptableObject.putProperty(m, key.toString(), ScriptableObject.getProperty(spec, key.toString()))
            }
        }
        val stateObj = NativeObject()
        fn(stateObj, "get") { args -> synchronized(state) { state[Context.toString(args.getOrNull(0))] } ?: Undefined.instance }
        fn(stateObj, "set") { args -> synchronized(state) { state[Context.toString(args.getOrNull(0))] = args.getOrNull(1) }; Undefined.instance }
        fn(stateObj, "delete") { args -> synchronized(state) { state.remove(Context.toString(args.getOrNull(0))) }; Undefined.instance }
        fn(stateObj, "clear") { synchronized(state) { state.clear() }; Undefined.instance }
        ScriptableObject.putProperty(scope, "state", stateObj)
    }

    private fun marker(kind: String) = NativeObject().also { ScriptableObject.putProperty(it, MARKER, kind) }

    companion object {
        const val MARKER = "__dta"

        fun fn(target: Scriptable, name: String, body: (Array<Any?>) -> Any?) {
            ScriptableObject.putProperty(target, name, object : BaseFunction() {
                override fun call(cx: Context, scope: Scriptable, thisObj: Scriptable?, args: Array<Any?>): Any? = body(args)
            })
        }
    }
}

/**
 * A compiled script, callable from any thread (each call enters its own Rhino context).
 * Calls never throw: failures come back as [ScriptResult.error] with no effect.
 */
class CompiledScript internal constructor(
    private val scope: ScriptableObject,
    private val globals: ScriptGlobals,
    val handlers: Set<ScriptHandler>,
    private val names: Map<ScriptHandler, String>,
) {
    fun onRequest(request: ScriptRequest): ScriptResult<RequestChange> =
        call(ScriptHandler.REQUEST, { cx, s -> arrayOf(Views.request(cx, s, request)) }) { cx, s, result, args ->
            Views.readRequest(cx, s, result, args[0] as NativeObject, request)
        }

    fun onResponse(response: ScriptResponse, request: ScriptRequest): ScriptResult<ResponseChange> =
        call(ScriptHandler.RESPONSE, { cx, s -> arrayOf(Views.response(cx, s, response), Views.request(cx, s, request)) }) { cx, s, result, args ->
            Views.readResponse(cx, s, result, args[0] as NativeObject, response)
        }

    fun onWsSend(message: ScriptMessage, connection: ScriptConnection): ScriptResult<MessageChange> = message(ScriptHandler.WS_SEND, message, connection)

    fun onWsReceive(message: ScriptMessage, connection: ScriptConnection): ScriptResult<MessageChange> = message(ScriptHandler.WS_RECEIVE, message, connection)

    private fun message(handler: ScriptHandler, message: ScriptMessage, connection: ScriptConnection) =
        call(handler, { cx, s -> arrayOf(Views.message(cx, s, message), Views.connection(connection)) }) { cx, s, result, args ->
            Views.readMessage(cx, s, result, args[0] as NativeObject, message)
        }

    private fun <T> call(
        handler: ScriptHandler,
        args: (Context, Scriptable) -> Array<Any?>,
        read: (Context, Scriptable, Any?, Array<Any?>) -> Effect<T>,
    ): ScriptResult<T> {
        val fn = ScriptableObject.getProperty(scope, names.getValue(handler)) as? Function ?: return ScriptResult(Effect.None)
        val state = CallState(handler)
        val start = System.nanoTime()
        var effect: Effect<T> = Effect.None
        var error: String? = null
        val cx = ScriptEngine.enter()
        globals.current.set(state)
        try {
            val callArgs = args(cx, scope)
            val result = fn.call(cx, scope, scope, callArgs)
            if (result == null) {
                error = "${names[handler]} returned null; return drop() to drop, or nothing to leave the traffic unchanged"
            } else {
                effect = read(cx, scope, result, callArgs)
            }
        } catch (t: Throwable) {
            error = describe(t)
        } finally {
            globals.current.remove()
            Context.exit()
        }
        val totalNanos = System.nanoTime() - start
        return ScriptResult(
            effect = if (error != null) Effect.None else effect,
            delayMs = state.delayNanos / 1_000_000,
            scriptMs = (totalNanos - state.delayNanos).coerceAtLeast(0) / 1_000_000,
            throttleBytesPerSecond = if (error != null) null else state.throttle,
            error = error?.let { "${names[handler]}: $it" },
        )
    }

    private fun describe(t: Throwable): String = when (t) {
        is WrappedException -> t.wrappedException.message ?: t.wrappedException.toString()
        is RhinoException -> "${t.details()} (line ${t.lineNumber()})"
        else -> t.message ?: t.toString()
    }
}

/** JS views of traffic, and reading the script's changes back. */
internal object Views {

    private fun headersToJs(headers: List<Header>): NativeObject = NativeObject().also { obj ->
        headers.groupBy { it.name }.forEach { (name, values) -> ScriptableObject.putProperty(obj, name, values.joinToString(", ") { it.value }) }
    }

    private fun headersFromJs(value: Any?): List<Header>? {
        val obj = value as? Scriptable ?: return null
        return obj.ids.flatMap { key ->
            val name = key.toString()
            when (val v = ScriptableObject.getProperty(obj, name)) {
                is NativeArray -> v.toArray().map { Header(name, Context.toString(it)) }
                else -> listOf(Header(name, Context.toString(v)))
            }
        }
    }

    private fun sameHeaders(original: List<Header>, read: List<Header>?): Boolean =
        read == null || headersToMap(original) == headersToMap(read)

    private fun headersToMap(headers: List<Header>) = headers.groupBy { it.name }.mapValues { (_, v) -> v.joinToString(", ") { it.value } }

    private fun bodyFunctions(cx: Context, scope: Scriptable, target: NativeObject, body: BodySource?, what: String) {
        ScriptGlobals.fn(target, "bytes") { body?.let { Context.javaToJS(it.bytes(), scope) } }
        ScriptGlobals.fn(target, "text") {
            when {
                body == null -> null
                body.binary -> throw IllegalStateException("$what body is binary (${body.contentType ?: "unknown type"}); use bytes()")
                else -> String(body.bytes(), Charsets.UTF_8)
            }
        }
        ScriptGlobals.fn(target, "json") {
            body?.let { NativeJSON.parse(Context.getCurrentContext(), scope, String(it.bytes(), Charsets.UTF_8)) { _, _, _, args -> args[1] } }
        }
    }

    fun request(cx: Context, scope: Scriptable, request: ScriptRequest): NativeObject = NativeObject().also { obj ->
        ScriptableObject.putProperty(obj, "url", request.url)
        ScriptableObject.putProperty(obj, "method", request.method)
        ScriptableObject.putProperty(obj, "headers", headersToJs(request.headers))
        ScriptableObject.putProperty(obj, "library", request.library)
        ScriptableObject.putProperty(obj, "id", request.id)
        bodyFunctions(cx, scope, obj, request.body, "request")
    }

    fun response(cx: Context, scope: Scriptable, response: ScriptResponse): NativeObject = NativeObject().also { obj ->
        ScriptableObject.putProperty(obj, "status", response.status)
        ScriptableObject.putProperty(obj, "headers", headersToJs(response.headers))
        bodyFunctions(cx, scope, obj, response.body, "response")
    }

    fun message(cx: Context, scope: Scriptable, message: ScriptMessage): NativeObject = NativeObject().also { obj ->
        ScriptableObject.putProperty(obj, "text", message.text)
        ScriptableObject.putProperty(obj, "binary", message.binary)
        ScriptGlobals.fn(obj, "bytes") { Context.javaToJS(message.bytes ?: message.text?.toByteArray(Charsets.UTF_8) ?: ByteArray(0), scope) }
    }

    fun connection(connection: ScriptConnection): NativeObject = NativeObject().also { obj ->
        ScriptableObject.putProperty(obj, "url", connection.url)
        ScriptableObject.putProperty(obj, "library", connection.library)
        ScriptableObject.putProperty(obj, "id", connection.id)
    }

    private fun marker(result: Any?): String? =
        (result as? Scriptable)?.let { ScriptableObject.getProperty(it, ScriptGlobals.MARKER) as? String }

    fun readRequest(cx: Context, scope: Scriptable, result: Any?, view: NativeObject, request: ScriptRequest): Effect<RequestChange> {
        when (marker(result)) {
            "drop" -> return Effect.Drop
            "respond" -> return Effect.Mock(scripted(cx, scope, result as Scriptable))
        }
        val obj = result as? Scriptable ?: return Effect.None
        val url = (ScriptableObject.getProperty(obj, "url") as? CharSequence)?.toString()?.takeIf { it != request.url }
        val method = (ScriptableObject.getProperty(obj, "method") as? CharSequence)?.toString()?.takeIf { it != request.method }
        val headers = headersFromJs(ScriptableObject.getProperty(obj, "headers")).takeUnless { sameHeaders(request.headers, it) }
        val body = assignedBody(cx, scope, obj, "body")
        if (url == null && method == null && headers == null && body == null) return Effect.None
        return Effect.Change(RequestChange(url, method, headers, body))
    }

    fun readResponse(cx: Context, scope: Scriptable, result: Any?, view: NativeObject, response: ScriptResponse): Effect<ResponseChange> {
        if (marker(result) == "drop") return Effect.Drop
        val obj = result as? Scriptable ?: return Effect.None
        val status = (ScriptableObject.getProperty(obj, "status") as? Number)?.toInt()?.takeIf { it != response.status }
        val headers = headersFromJs(ScriptableObject.getProperty(obj, "headers")).takeUnless { sameHeaders(response.headers, it) }
        val body = assignedBody(cx, scope, obj, "body")
        if (status == null && headers == null && body == null) return Effect.None
        return Effect.Change(ResponseChange(status, headers, body))
    }

    fun readMessage(cx: Context, scope: Scriptable, result: Any?, view: NativeObject, message: ScriptMessage): Effect<MessageChange> {
        if (marker(result) == "drop") return Effect.Drop
        val obj = result as? Scriptable ?: return Effect.None
        val text = (ScriptableObject.getProperty(obj, "text") as? CharSequence)?.toString()?.takeIf { it != message.text }
        val bytesValue = ScriptableObject.getProperty(obj, "bytes")
        val bytes = if (bytesValue is Function) null else toBytes(cx, scope, bytesValue)
        if (text == null && bytes == null) return Effect.None
        return Effect.Change(MessageChange(text, bytes))
    }

    private fun scripted(cx: Context, scope: Scriptable, spec: Scriptable): ScriptedResponse = ScriptedResponse(
        status = (ScriptableObject.getProperty(spec, "status") as? Number)?.toInt() ?: 200,
        headers = headersFromJs(ScriptableObject.getProperty(spec, "headers")) ?: emptyList(),
        body = assignedBody(cx, scope, spec, "body") ?: ByteArray(0),
    )

    /** A `body` the script assigned (string, bytes, array of numbers, or an object as JSON); null if none. */
    private fun assignedBody(cx: Context, scope: Scriptable, obj: Scriptable, name: String): ByteArray? {
        if (!ScriptableObject.hasProperty(obj, name)) return null
        return toBytes(cx, scope, ScriptableObject.getProperty(obj, name))
    }

    private fun toBytes(cx: Context, scope: Scriptable, value: Any?): ByteArray? = when (value) {
        null, Undefined.instance, Scriptable.NOT_FOUND -> null
        is CharSequence -> value.toString().toByteArray(Charsets.UTF_8)
        is ConsString -> value.toString().toByteArray(Charsets.UTF_8)
        is NativeJavaArray -> value.unwrap() as? ByteArray
        is NativeArray -> value.toArray().map { Context.toNumber(it).toInt().toByte() }.toByteArray()
        is Scriptable -> (NativeJSON.stringify(cx, scope, value, null, null) as? CharSequence)?.toString()?.toByteArray(Charsets.UTF_8)
        else -> Context.toString(value).toByteArray(Charsets.UTF_8)
    }
}

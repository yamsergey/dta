package io.yamsergey.dta.daemon.network.proto

import com.google.protobuf.DynamicMessage
import com.google.protobuf.util.JsonFormat
import io.opentelemetry.proto.collector.logs.v1.ExportLogsServiceRequest
import io.opentelemetry.proto.collector.metrics.v1.ExportMetricsServiceRequest
import io.opentelemetry.proto.collector.trace.v1.ExportTraceServiceRequest
import io.opentelemetry.proto.trace.v1.ResourceSpans
import io.opentelemetry.proto.trace.v1.ScopeSpans
import io.opentelemetry.proto.trace.v1.Span
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/** The pinned protobuf runtime accepts the OTLP gencode descriptors (plan: versions checked by a test). */
class ProtoRuntimeCompatTest {

    @Test
    fun `OTLP descriptors load under the pinned runtime`() {
        assertEquals("ExportTraceServiceRequest", ExportTraceServiceRequest.getDescriptor().name)
        assertEquals("ExportMetricsServiceRequest", ExportMetricsServiceRequest.getDescriptor().name)
        assertEquals("ExportLogsServiceRequest", ExportLogsServiceRequest.getDescriptor().name)
    }

    @Test
    fun `a dynamic message round-trips generated bytes and prints as JSON`() {
        val request = ExportTraceServiceRequest.newBuilder().addResourceSpans(
            ResourceSpans.newBuilder().addScopeSpans(ScopeSpans.newBuilder().addSpans(Span.newBuilder().setName("checkout"))),
        ).build()
        val dynamic = DynamicMessage.parseFrom(ExportTraceServiceRequest.getDescriptor(), request.toByteArray())
        assertContentEquals(request.toByteArray(), dynamic.toByteArray())
        assertTrue("\"name\": \"checkout\"" in JsonFormat.printer().print(dynamic))
    }
}

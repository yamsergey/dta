    try {
        settings.dependencyResolutionManagement.repositories {
            mavenCentral()$snapshotSettingsRepos
        }
    } catch (Throwable t) {
        settings.gradle.rootProject { it.logger.warn('[DTA] could not add the DTA repositories: ' + t) }
    }
}

allprojects { project ->
    project.pluginManager.withPlugin('com.android.application') {
        def found = java.util.Collections.synchronizedList([])
        dtaVariants[project.path] = found
        try {
            def components = project.extensions.getByName('androidComponents')
            components.onVariants(components.selector().all()) { variant ->
                try {
                    found << [name: variant.name, buildType: variant.buildType, flavors: variant.productFlavors.collect { it.second }, applicationId: variant.applicationId.orNull]
                } catch (Throwable t) {
                    project.logger.warn('[DTA] could not read the variant ' + variant.name + ': ' + t)
                }
            }
        } catch (Throwable t) {
            project.logger.warn('[DTA] could not list the variants of ' + project.path + ': ' + t)
        }
        project.afterEvaluate {
            try {
                dtaOutcomes[project.path] = dtaInject(project, dtaCoordinate, dtaSidekickOn, dtaToolingOn, found)
            } catch (Throwable t) {
                dtaOutcomes[project.path] = [outcome: 'unsupported', reason: t.toString()]
            }
            def outcome = dtaOutcomes[project.path]
            project.logger.lifecycle('[DTA] ' + project.path + ': ' + outcome.outcome + (outcome.reason ? ' (' + outcome.reason + ')' : '') +
                (outcome.tooling ? '; Compose tooling data: ' + outcome.tooling.outcome + (outcome.tooling.reason ? ' (' + outcome.tooling.reason + ')' : '') : ''))
        }
    }
}

gradle.projectsEvaluated {
    try {
        def projects = dtaOutcomes.collect { p, o ->
            def debuggable = o.debuggable ?: [:]
            def variants = (dtaVariants[p] ?: []).collect { v -> v + [debuggable: debuggable[v.buildType] == true] }.sort { it.name }
            [path: p, outcome: o.outcome, reason: o.reason, tooling: o.tooling, variants: variants]
        }.sort { it.path }
        def run = null
        if (dtaRunRequest) run = dtaSelect(dtaRunData ?: [:], projects.collectEntries { [(it.path): it.variants] })
        def text = groovy.json.JsonOutput.toJson([version: '@VERSION@', projects: projects, run: run])
        def path = gradle.startParameter.projectProperties['${config.reportProperty}']
        if (path) {
            def file = new File(path)
            file.parentFile?.mkdirs()
            file.text = text
        }
        if (dtaRunRequest) {
            def task = run.outcome == 'selected' ? run.task : null
            def tasks = task ? [task] : []
            if (task && dtaRunData?.reinstall == true && dtaRunData?.buildOnly != true) {
                // `--reinstall`: uninstall (deleting the app's data) only once the app is built.
                def module = gradle.rootProject.project(run.module)
                def name = run.variant.substring(0, 1).toUpperCase() + run.variant.substring(1)
                module.tasks.named('uninstall' + name).configure { it.mustRunAfter('package' + name, 'assemble' + name) }
                module.tasks.named('install' + name).configure { it.mustRunAfter('uninstall' + name) }
                tasks = [task.replace(':install' + name, ':uninstall' + name), task]
            }
            gradle.rootProject.tasks.register('dtaRun') { t ->
                t.group = 'dta'
                t.description = 'Builds or installs the variant DTA selected (dta run).'
                if (tasks) t.dependsOn(tasks)
                // Written again at execution: a reused configuration cache skips this block.
                t.doLast {
                    if (path) {
                        def file = new File(path)
                        file.parentFile?.mkdirs()
                        file.text = text
                    }
                }
            }
        }
    } catch (Throwable t) {
        gradle.rootProject.logger.warn('[DTA] could not write the injection report: ' + t)
    }
}

def dtaInject(Project project, String coordinate, boolean sidekickOn, boolean toolingOn, List variants) {
    def android = project.extensions.getByName('android')
    def types = android.buildTypes.matching { it.debuggable }.collect { it }
    def result = [debuggable: android.buildTypes.collectEntries { [(it.name): it.debuggable == true] }]
    if (types.isEmpty()) return result + [outcome: 'unsupported', reason: 'no debuggable build type', tooling: null]
    def runtime = dtaRuntime(project, types.first(), variants)

    def declared = project.configurations.any { c ->
        c.dependencies.any { it.group == '${InjectionConfig.GROUP}' && it.name == '${InjectionConfig.ARTIFACT}' }
    }
    if (declared) {
        result += [outcome: 'project-provided', reason: null]
    } else if (!sidekickOn) {
        result += [outcome: 'off', reason: null]
    } else {$snapshotProjectSetup
        // Resolve first, as the debug runtime would: an unresolvable sidekick must not fail the build.
        def probe = project.configurations.detachedConfiguration(project.dependencies.create(coordinate))
        dtaAttributes(probe, runtime)$snapshotProbe
        def failed = probe.incoming.resolutionResult.allDependencies.find { it instanceof UnresolvedDependencyResult }
        if (failed != null) {
            result += [outcome: 'unresolved', reason: dtaCause(failed.failure)]
        } else {
            types.each { bt -> project.dependencies.add(bt.name + 'Implementation', coordinate) }
            result += [outcome: 'injected', reason: null]
        }
    }
    try {
        result.tooling = toolingOn ? dtaTooling(project, android, types, runtime) : [outcome: 'off', version: null, reason: null]
    } catch (Throwable t) {
        result.tooling = [outcome: 'unresolved', version: null, reason: t.toString()]
    }
    return result
}

// The runtime classpath of the build type's first variant: its attributes are what the probes resolve with.
def dtaRuntime(Project project, bt, List variants) {
    def variant = variants.find { it.buildType == bt.name }
    return project.configurations.findByName((variant ? variant.name : bt.name) + 'RuntimeClasspath')
}

def dtaAttributes(probe, runtime) {
    if (runtime != null) {
        probe.attributes { attrs ->
            runtime.attributes.keySet().each { key -> attrs.attribute(key, runtime.attributes.getAttribute(key)) }
        }
    }
}

// Compose's tooling data (layout source information), added versionless: Compose UI's own
// constraints pick the app's version. Probed on a copy of the app's declared external
// dependencies (resolving the app's configurations here would lock them); when the
// constraint does not apply, the probe's Compose UI version is used explicitly.
def dtaTooling(Project project, android, List types, runtime) {
    def compose = project.pluginManager.hasPlugin('org.jetbrains.kotlin.plugin.compose')
    try {
        compose = compose || android.buildFeatures.compose == true
    } catch (Throwable ignored) {
        // No buildFeatures.compose on this AGP: the plugin check stands.
    }
    if (!compose) return [outcome: 'not-applicable', version: null, reason: null]
    def names = { bt -> ['implementation', 'api', 'runtimeOnly', bt.name + 'Implementation', bt.name + 'Api', bt.name + 'RuntimeOnly'] }
    def declares = { bt ->
        names(bt).any { n ->
            def c = project.configurations.findByName(n)
            c != null && c.dependencies.any { it.group == 'androidx.compose.ui' && (it.name == 'ui-tooling' || it.name == 'ui-tooling-data') }
        }
    }
    if (types.every { declares(it) }) return [outcome: 'project-provided', version: null, reason: null]

    def external = names(types.first()).collectMany { n ->
        def c = project.configurations.findByName(n)
        c == null ? [] : c.dependencies.findAll { it instanceof ExternalModuleDependency }.collect { it.copy() }
    }
    def resolve = { String notation ->
        def probe = project.configurations.detachedConfiguration(*(external + [project.dependencies.create(notation)]))
        dtaAttributes(probe, runtime)
        probe.incoming.resolutionResult
    }
    def tooling = { result -> result.allComponents.find { it.moduleVersion?.group == 'androidx.compose.ui' && it.moduleVersion?.name == 'ui-tooling-data' } }
    def unresolved = { result -> result.allDependencies.find { it instanceof UnresolvedDependencyResult } }

    def notation = '${InjectionConfig.TOOLING_COORDINATE}'
    def result = resolve(notation)
    def found = unresolved(result) == null ? tooling(result) : null
    if (found == null) {
        def ui = result.allComponents.find { it.moduleVersion?.group == 'androidx.compose.ui' && it.moduleVersion?.name == 'ui' }
        if (ui == null) return [outcome: 'unresolved', version: null, reason: 'Compose UI is not among the declared dependencies of ' + project.path]
        notation = notation + ':' + ui.moduleVersion.version
        result = resolve(notation)
        def failed = unresolved(result)
        if (failed != null) return [outcome: 'unresolved', version: null, reason: dtaCause(failed.failure)]
        found = tooling(result)
    }
    types.findAll { !declares(it) }.each { bt -> project.dependencies.add(bt.name + 'Implementation', notation) }
    return [outcome: 'injected', version: found?.moduleVersion?.version, reason: null]
}

// The module and variant `dta run` builds (010 contracts/injection.md): the request names
// them, or the only app module and its debug (or only debuggable) variant are taken.
def dtaSelect(Map request, Map apps) {
    if (apps.isEmpty()) return [outcome: 'no-app-module', reason: 'no project applies com.android.application']
    def module = request.module
    if (module) {
        if (!apps.containsKey(module)) return [outcome: 'module-not-found', choices: apps.keySet().sort()]
    } else if (apps.size() > 1) {
        return [outcome: 'module-required', choices: apps.keySet().sort()]
    } else {
        module = apps.keySet().first()
    }
    def variants = apps[module]
    def chosen
    if (request.variant) {
        chosen = variants.find { it.name == request.variant }
        if (chosen == null) return [outcome: 'variant-not-found', module: module, choices: variants.collect { it.name }.sort()]
        if (!chosen.debuggable) return [outcome: 'not-debuggable', module: module, variant: chosen.name,
            reason: 'variant ' + chosen.name + ' uses build type ' + chosen.buildType + ', which is not debuggable']
    } else {
        chosen = variants.find { it.name == 'debug' && it.debuggable }
        if (chosen == null) {
            def candidates = variants.findAll { it.debuggable }
            if (candidates.size() != 1) return [outcome: 'variant-required', module: module, choices: candidates.collect { it.name }.sort()]
            chosen = candidates.first()
        }
    }
    def verb = request.buildOnly ? 'assemble' : 'install'
    def task = (module == ':' ? '' : module) + ':' + verb + chosen.name.substring(0, 1).toUpperCase() + chosen.name.substring(1)
    return [outcome: 'selected', module: module, variant: chosen.name, task: task, applicationId: chosen.applicationId]
}

// "Could not find …" and where Gradle looked, on one line.
def dtaCause(Throwable failure) {
    def lines = (failure.message ?: failure.toString()).readLines()
    def searched = lines.findAll { it.trim().startsWith('- ') }.collect { it.trim().substring(2) }
    return lines.first().trim() + (searched ? ' (searched: ' + searched.join(', ') + ')' : '')
}$snapshotFunctions
""".trimStart().replace("@VERSION@", config.version)
    }


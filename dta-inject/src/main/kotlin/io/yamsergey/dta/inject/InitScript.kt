package io.yamsergey.dta.inject

/**
 * The Gradle init script that adds the DTA sidekick to the debuggable builds of Android apps
 * (009 research R10; 010 contracts/injection.md, v2), for the IDE (`--init-script`) and `dta run`.
 *
 * - Only `com.android.application` projects, only debuggable build types (`<type>Implementation`):
 *   release never sees it.
 * - Compose apps without Compose's tooling data get it too, in their own Compose version.
 * - Run mode (`dta run`) selects the module and variant and registers `dtaRun`.
 * - A project that declares the sidekick itself is left alone (`project-provided`).
 * - The sidekick is resolved first in a detached configuration with the debug runtime's
 *   attributes; when that fails nothing is added (`unresolved`, with the cause).
 * - Every callback is guarded: an exception is reported (`unsupported`), never thrown.
 * - Repositories as the original plugin: settings-level, and project-level for snapshots
 *   where the project's own repositories win (`RepositoriesMode`).
 */
object InitScript {

    fun render(config: InjectionConfig): String {
        // A snapshot built on this machine (publishToMavenLocal) wins over the published one.
        val snapshotSettingsRepos = if (config.snapshot) """
                    mavenLocal()
                    maven { url = '$SNAPSHOT_REPOSITORY' }""" else ""
        val snapshotProjectSetup = if (config.snapshot) """
        dtaSnapshotRepositories(project)""" else ""
        val snapshotProbe = if (config.snapshot) """
        probe.resolutionStrategy.cacheChangingModulesFor(0, 'seconds')""" else ""
        val snapshotFunctions = if (config.snapshot) """

// Projects in the default PREFER_PROJECT mode ignore settings repositories once they declare
// their own, so those get ours too; a project that declares none uses the settings ones (ours
// among them) — adding a repository to it would hide google() and mavenCentral() from it.
// FAIL_ON_PROJECT_REPOS and PREFER_SETTINGS take the settings-level ones above.
def dtaSnapshotRepositories(Project project) {
    def needed = true
    try {
        def mode = project.gradle.settings.dependencyResolutionManagement.repositoriesMode.get()
        needed = mode != org.gradle.api.initialization.resolve.RepositoriesMode.FAIL_ON_PROJECT_REPOS &&
            mode != org.gradle.api.initialization.resolve.RepositoriesMode.PREFER_SETTINGS
    } catch (Throwable ignored) {
        // Gradle without repositoriesMode: projects may declare repositories.
    }
    if (needed && !project.repositories.isEmpty()) {
        project.repositories.mavenLocal()
        project.repositories.maven { url = '$SNAPSHOT_REPOSITORY' }
    }
    // A new snapshot is picked up on the next build, without clearing caches.
    project.configurations.configureEach { it.resolutionStrategy.cacheChangingModulesFor(0, 'seconds') }
}""" else ""

        return """
// Generated by DTA (dta-inject) for dta-sidekick @VERSION@. Do not edit: it is rewritten.
// Adds the sidekick (and Compose's tooling data) to the debuggable builds of Android apps;
// never fails a build. What it did per app is written to the file named by
// -P${config.reportProperty}. With -P${config.runProperty}=<request.json> (`dta run`) it also
// selects the module and variant and registers `dtaRun`, which builds or installs them.
import org.gradle.api.artifacts.ExternalModuleDependency
import org.gradle.api.artifacts.result.UnresolvedDependencyResult

def dtaCoordinate = '${config.coordinate}'
def dtaToolingOn = gradle.startParameter.projectProperties['${config.toolingProperty}'] != 'false'
def dtaRunRequest = gradle.startParameter.projectProperties['${config.runProperty}']
def dtaRunData = null
try {
    if (dtaRunRequest) dtaRunData = new groovy.json.JsonSlurper().parse(new File(dtaRunRequest))
} catch (Throwable t) {
    gradle.rootProject { it.logger.warn('[DTA] could not read the run request ' + dtaRunRequest + ': ' + t) }
}
// `dta run --no-inject`: select and build, but add nothing.
def dtaSidekickOn = dtaRunData == null || dtaRunData.inject != false
def dtaOutcomes = new java.util.concurrent.ConcurrentHashMap<String, Map>()
def dtaVariants = new java.util.concurrent.ConcurrentHashMap<String, List>()


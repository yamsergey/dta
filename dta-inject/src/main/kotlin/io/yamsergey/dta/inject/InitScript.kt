package io.yamsergey.dta.inject

/**
 * The Gradle init script that adds the DTA sidekick to the debug builds of Android apps
 * (research R10, contracts/injection.md), for the IDE (`--init-script`) and `dta run`.
 *
 * - Only `com.android.application` projects, only `debugImplementation`: release never sees it.
 * - A project that declares the sidekick itself is left alone (`project-provided`).
 * - The sidekick is resolved first in a detached configuration with the debug runtime's
 *   attributes; when that fails nothing is added (`unresolved`, with the cause).
 * - Every callback is guarded: an exception is reported (`unsupported`), never thrown.
 * - Repositories as the original plugin: settings-level, and project-level for snapshots
 *   where the project's own repositories win (`RepositoriesMode`).
 */
object InitScript {

    fun render(config: InjectionConfig): String {
        val snapshotSettingsRepos = if (config.snapshot) """
                    maven { url = '$SNAPSHOT_REPOSITORY' }
                    mavenLocal()""" else ""
        val snapshotProjectSetup = if (config.snapshot) """
        dtaSnapshotRepositories(project)""" else ""
        val snapshotProbe = if (config.snapshot) """
        probe.resolutionStrategy.cacheChangingModulesFor(0, 'seconds')""" else ""
        val snapshotFunctions = if (config.snapshot) """

// Projects in the default PREFER_PROJECT mode ignore settings repositories once they declare
// their own; FAIL_ON_PROJECT_REPOS and PREFER_SETTINGS take the settings-level ones above.
def dtaSnapshotRepositories(Project project) {
    def needed = true
    try {
        def mode = project.gradle.settings.dependencyResolutionManagement.repositoriesMode.get()
        needed = mode != org.gradle.api.initialization.resolve.RepositoriesMode.FAIL_ON_PROJECT_REPOS &&
            mode != org.gradle.api.initialization.resolve.RepositoriesMode.PREFER_SETTINGS
    } catch (Throwable ignored) {
        // Gradle without repositoriesMode: projects may declare repositories.
    }
    if (needed) {
        project.repositories.maven { url = '$SNAPSHOT_REPOSITORY' }
        project.repositories.mavenLocal()
    }
    // A new snapshot is picked up on the next build, without clearing caches.
    project.configurations.configureEach { it.resolutionStrategy.cacheChangingModulesFor(0, 'seconds') }
}""" else ""

        return """
// Generated by DTA (dta-inject) for dta-sidekick @VERSION@. Do not edit: it is rewritten.
// Adds the sidekick to the debug builds of Android apps; never fails a build. What it did per
// app is written to the file named by -P${config.reportProperty}.
import org.gradle.api.artifacts.result.UnresolvedDependencyResult

def dtaCoordinate = '${config.coordinate}'
def dtaOutcomes = new java.util.concurrent.ConcurrentHashMap<String, Map>()

beforeSettings { settings ->
    try {
        settings.dependencyResolutionManagement.repositories {
            mavenCentral()$snapshotSettingsRepos
        }
    } catch (Throwable t) {
        settings.gradle.rootProject { it.logger.warn('[DTA] could not add the DTA repositories: ' + t) }
    }
}

allprojects { project ->
    project.pluginManager.withPlugin('com.android.application') {
        project.afterEvaluate {
            try {
                dtaOutcomes[project.path] = dtaInject(project, dtaCoordinate)
            } catch (Throwable t) {
                dtaOutcomes[project.path] = [outcome: 'unsupported', reason: t.toString()]
            }
            def outcome = dtaOutcomes[project.path]
            project.logger.lifecycle('[DTA] ' + project.path + ': ' + outcome.outcome + (outcome.reason ? ' (' + outcome.reason + ')' : ''))
        }
    }
}

gradle.projectsEvaluated {
    try {
        def path = gradle.startParameter.projectProperties['${config.reportProperty}']
        if (path) {
            def file = new File(path)
            file.parentFile?.mkdirs()
            def projects = dtaOutcomes.collect { p, o -> [path: p, outcome: o.outcome, reason: o.reason] }.sort { it.path }
            file.text = groovy.json.JsonOutput.toJson([version: '@VERSION@', projects: projects])
        }
    } catch (Throwable t) {
        gradle.rootProject.logger.warn('[DTA] could not write the injection report: ' + t)
    }
}

def dtaInject(Project project, String coordinate) {
    def declared = project.configurations.any { c ->
        c.dependencies.any { it.group == '${InjectionConfig.GROUP}' && it.name == '${InjectionConfig.ARTIFACT}' }
    }
    if (declared) return [outcome: 'project-provided', reason: null]$snapshotProjectSetup

    // Resolve first, as the debug runtime would: an unresolvable sidekick must not fail the build.
    def probe = project.configurations.detachedConfiguration(project.dependencies.create(coordinate))
    def runtime = project.configurations.findByName('debugRuntimeClasspath')
    if (runtime != null) {
        probe.attributes { attrs ->
            runtime.attributes.keySet().each { key -> attrs.attribute(key, runtime.attributes.getAttribute(key)) }
        }
    }$snapshotProbe
    def failed = probe.incoming.resolutionResult.allDependencies.find { it instanceof UnresolvedDependencyResult }
    if (failed != null) return [outcome: 'unresolved', reason: dtaCause(failed.failure)]

    project.dependencies.add('debugImplementation', coordinate)
    return [outcome: 'injected', reason: null]
}

// "Could not find …" and where Gradle looked, on one line.
def dtaCause(Throwable failure) {
    def lines = (failure.message ?: failure.toString()).readLines()
    def searched = lines.findAll { it.trim().startsWith('- ') }.collect { it.trim().substring(2) }
    return lines.first().trim() + (searched ? ' (searched: ' + searched.join(', ') + ')' : '')
}$snapshotFunctions
""".trimStart().replace("@VERSION@", config.version)
    }

    const val SNAPSHOT_REPOSITORY = "https://central.sonatype.com/repository/maven-snapshots/"
}
